// ─────────────────────────────────────────────────────────────────────────
// Seeder
// ─────────────────────────────────────────────────────────────────────────
async function main() {
  console.log("\n🌱 Seeding coloring-book categories into Turso (libSQL)\n");

  // Dynamic import ensures env vars are set before turso.ts singleton init.
  const {
    ensureCategorySchema,
    createCategory,
    createItemsBulk,
    isCategorySchemaSeeded,
    getCategory,
    isTursoConfigured,
  } = await import("../src/lib/category-store");

  if (!isTursoConfigured()) {
    console.error("❌ Turso not configured — set TURSO_DATABASE_URL.");
    process.exit(1);
  }

  await ensureCategorySchema();
  console.log("✓ Schema ensured (categories + items tables)");

  // Resumable: only early-exit if EVERY category from the seed list is already
  // in the DB. If only SOME exist (e.g. previous run crashed mid-way), fall
  // through to the loop — getCategory(slug) will skip already-created ones.
  if (await isCategorySchemaSeeded()) {
    let existingCount = 0;
    for (const c of CATEGORIES) {
      if (await getCategory(c.slug)) existingCount++;
    }
    if (existingCount === CATEGORIES.length) {
      console.log(
        `✓ All ${CATEGORIES.length} categories already seeded — skipping (idempotent).`
      );
      return;
    }
    console.log(
      `⋯  Found ${existingCount}/${CATEGORIES.length} existing categories — resuming from where we left off.`
    );
  }

  // Sanity check: slug uniqueness within our seed list
  const slugSet = new Set<string>();
  for (const c of CATEGORIES) {
    if (slugSet.has(c.slug)) {
      console.error(`❌ Duplicate slug in seed list: ${c.slug}`);
      process.exit(1);
    }
    slugSet.add(c.slug);
  }

  // Per-category: ensure items are unique within the list
  for (const c of CATEGORIES) {
    const seen = new Set<string>();
    for (const it of c.items) {
      if (seen.has(it)) {
        console.error(`❌ Duplicate item "${it}" in category "${c.slug}"`);
        process.exit(1);
      }
      seen.add(it);
    }
  }

  console.log(
    `\n📦 Seeding ${CATEGORIES.length} categories (each with ~40 items)…\n`
  );

  let totalCats = 0;
  let totalItems = 0;
  let skipped = 0;

  for (let i = 0; i < CATEGORIES.length; i++) {
    const cat = CATEGORIES[i];

    // Resumable: skip if this slug already exists
    const existing = await getCategory(cat.slug);
    if (existing) {
      console.log(
        `⏭  [${i + 1}/${CATEGORIES.length}] ${cat.slug} already exists — skipping`
      );
      skipped++;
      totalCats++;
      totalItems += existing.itemCount;
      continue;
    }

    try {
      const created = await createCategory({
        name: cat.name,
        slug: cat.slug,
        emoji: cat.emoji,
        themeColor: cat.themeColor,
        description: cat.description,
        isBuiltin: true,
      });

      const count = await createItemsBulk(
        created.id,
        cat.items.map((name) => ({ name }))
      );

      totalCats++;
      totalItems += count;
      console.log(
        `✓ [${i + 1}/${CATEGORIES.length}] ${cat.name} (${cat.slug}): ${count} items`
      );
    } catch (e) {
      console.error(
        `✗ [${i + 1}/${CATEGORIES.length}] ${cat.slug} FAILED:`,
        e instanceof Error ? e.message : e
      );
    }
  }

  console.log(
    `\n✨ Done. Seeded ${totalCats} categories (${skipped} skipped) with ${totalItems} items total.`
  );
}

main().catch((err) => {
  console.error("❌ Seeder crashed:", err);
  process.exit(1);
});
